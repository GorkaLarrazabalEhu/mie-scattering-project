"""
plot_radius_sweep.py
--------------------
Reads an MSTM output file generated by a radius sweep and produces:

  1. Efficiencies vs radius  (Qext / Qabs / Qsca)
  2. S₁₁ polar diagram  —  linear and log scale
  3. Individual polar grid  —  one subplot per radius step

Usage:
    python plot_radius_sweep.py <output.dat> [config.json]

    <output.dat>   MSTM output file  (required)
    [config.json]  Simulation config (optional).
                   If provided, radius values are read from it.
                   Otherwise the x-axis shows run index.
"""

