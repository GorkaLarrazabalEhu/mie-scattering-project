def set_fig_title(fig, title: str):
    try:
        fig.canvas.manager.set_window_title(title)
    except Exception:
        pass


def auto_save_or_show(fig, name: str, save_dir: str = "."):
    """Save PNG and show interactively, unless SHOW_ONLY is True."""
    if not SHOW_ONLY:
        os.makedirs(save_dir, exist_ok=True)
        outfile = os.path.join(save_dir, f"{name}.png")
        fig.savefig(outfile, dpi=150, bbox_inches="tight")
        print(f"  -> Saved: {outfile}")
    plt.show(block=False)


# =============================================================================
#  Parsing
# =============================================================================

EFF_RE       = re.compile(r"total extinction.*efficiencies\s*\(unpol, par, perp")
EFF_RE_UNPOL = re.compile(r"total extinction.*efficiencies\s*\(unpolarized")
SCAT_RE      = re.compile(r"scattering matrix in incident plane")
THETA_HDR_RE = re.compile(r"^\s*theta\s+11\b")


def _parse_eff_line(vals):
    """Return efficiency dict from a list of 3 or 9 floats."""
    if len(vals) == 9:
        return {
            "unpol": {"Qext": vals[0], "Qabs": vals[1], "Qsca": vals[2]},
            "par":   {"Qext": vals[3], "Qabs": vals[4], "Qsca": vals[5]},
            "perp":  {"Qext": vals[6], "Qabs": vals[7], "Qsca": vals[8]},
        }
    _nan = {"Qext": np.nan, "Qabs": np.nan, "Qsca": np.nan}
    if len(vals) == 3:
        d = {"Qext": vals[0], "Qabs": vals[1], "Qsca": vals[2]}
        return {"unpol": d, "par": d.copy(), "perp": d.copy()}
    return {"unpol": _nan.copy(), "par": _nan.copy(), "perp": _nan.copy()}


def _empty_eff():
    _nan = {"Qext": np.nan, "Qabs": np.nan, "Qsca": np.nan}
    return {"unpol": _nan.copy(), "par": _nan.copy(), "perp": _nan.copy()}


def parse_runs(filepath: str) -> list:
    """
    Parse MSTM output file.  Returns a list of run dicts:
        {
          "eff":         { "unpol": {...}, "par": {...}, "perp": {...} },
          "degreeTheta": ndarray | None,
          "radianTheta": ndarray | None,
          "S11":         ndarray | None,
        }
    """
    with open(filepath, "r", errors="ignore") as fh:
        lines = fh.readlines()

    runs        = []
    pending_eff = None
    i = 0

    while i < len(lines):
        line = lines[i]

        # ── Efficiencies ──────────────────────────────────────────────────
        if EFF_RE.search(line):
            try:
                vals = list(map(float, lines[i + 1].split()))
                pending_eff = _parse_eff_line(vals)
            except (ValueError, IndexError):
                pass
            i += 2
            continue

        if EFF_RE_UNPOL.search(line):
            try:
                vals = list(map(float, lines[i + 1].split()))
                pending_eff = _parse_eff_line(vals)
            except (ValueError, IndexError):
                pass
            i += 2
            continue

        # ── Scattering matrix ─────────────────────────────────────────────
        if SCAT_RE.search(line):
            # advance to column header  "theta  11  12 ..."
            j = i + 1
            while j < len(lines) and not THETA_HDR_RE.match(lines[j]):
                j += 1
            j += 1   # first data row

            thetas, s11 = [], []
            while j < len(lines):
                stripped = lines[j].strip()
                if not stripped or stripped.startswith("*"):
                    break
                parts = stripped.split()
                try:
                    thetas.append(float(parts[0]))
                    s11.append(float(parts[1]))
                except (ValueError, IndexError):
                    break
                j += 1

            if thetas:
                theta_deg = np.array(thetas)
                runs.append({
                    "eff":         pending_eff or _empty_eff(),
                    "degreeTheta": theta_deg,
                    "radianTheta": np.deg2rad(theta_deg),
                    "S11":         np.array(s11),
                })
                pending_eff = None
            i = j
            continue

        i += 1

    # A run with only efficiency data (no scattering matrix)
    if pending_eff is not None:
        runs.append({
            "eff":         pending_eff,
            "degreeTheta": None,
            "radianTheta": None,
            "S11":         None,
        })

    return runs


