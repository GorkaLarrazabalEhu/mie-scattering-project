def load_radii_from_config(config_path: str, n_runs: int):
    """Read radius sweep values from config.json.  Returns ndarray or None."""
    if not os.path.exists(config_path):
        return None
    try:
        with open(config_path) as fh:
            cfg = json.load(fh)
        rs = cfg.get("radius_sweep", {})
        if not rs.get("enabled", False):
            return None
        radii = np.linspace(float(rs["min"]), float(rs["max"]), int(rs["n"]))
        if len(radii) != n_runs:
            print(f"  [warning] config.json has {len(radii)} steps "
                  f"but {n_runs} runs found.")
        return radii
    except Exception as exc:
        print(f"  [warning] Could not read config.json: {exc}")
        return None


def writable_dir(path: str) -> str:
    """Return path if writable, otherwise current working directory."""
    try:
        test = os.path.join(path, ".write_test")
        open(test, "w").close()
        os.remove(test)
        return path
    except OSError:
        return os.path.abspath(".")


